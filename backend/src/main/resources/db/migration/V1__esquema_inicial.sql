-- Esquema inicial del Sistema de Gestión de Parqueadero Institucional FET.
-- Replica el esquema que hasta ahora generaba Hibernate con ddl-auto=update,
-- a partir de las entidades JPA en adapter/out/persistence/entity.
-- Todos los identificadores son UUID generados por Hibernate (GenerationType.UUID),
-- por lo que las columnas ID no requieren DEFAULT ni extensiones de PostgreSQL.

CREATE TABLE PROPIETARIO (
    ID                 UUID PRIMARY KEY,
    PRIMER_NOMBRE      VARCHAR(80)  NOT NULL,
    PRIMER_APELLIDO    VARCHAR(80)  NOT NULL,
    NOMBRE_COMPLETO    VARCHAR(165) NOT NULL,
    NUMERO_DOCUMENTO   VARCHAR(30)  NOT NULL,
    TIPO_USUARIO       VARCHAR(30)  NOT NULL,
    TELEFONO           VARCHAR(30),
    CORREO             VARCHAR(120),
    CONSTRAINT UK_PROPIETARIO_NUMERO_DOCUMENTO UNIQUE (NUMERO_DOCUMENTO)
);

CREATE TABLE ESPACIO (
    ID      UUID PRIMARY KEY,
    NUMERO  VARCHAR(10) NOT NULL,
    ESTADO  VARCHAR(30) NOT NULL,
    CONSTRAINT UK_ESPACIO_NUMERO UNIQUE (NUMERO)
);

CREATE TABLE VEHICULO (
    ID              UUID PRIMARY KEY,
    PLACA           VARCHAR(20) NOT NULL,
    TIPO            VARCHAR(20) NOT NULL,
    MARCA           VARCHAR(80) NOT NULL,
    MODELO          VARCHAR(80),
    ESTADO          VARCHAR(20) NOT NULL,
    PROPIETARIO_ID  UUID NOT NULL,
    CONSTRAINT UK_VEHICULO_PLACA UNIQUE (PLACA),
    CONSTRAINT FK_VEHICULO_PROPIETARIO FOREIGN KEY (PROPIETARIO_ID) REFERENCES PROPIETARIO (ID)
);

CREATE INDEX IDX_VEHICULO_PROPIETARIO ON VEHICULO (PROPIETARIO_ID);
CREATE INDEX IDX_VEHICULO_PLACA ON VEHICULO (PLACA);

CREATE TABLE MOVIMIENTO (
    ID                          UUID PRIMARY KEY,
    VEHICULO_ID                 UUID NOT NULL,
    ESPACIO_ID                  UUID NOT NULL,
    FECHA_ENTRADA               TIMESTAMP WITH TIME ZONE NOT NULL,
    FECHA_SALIDA                TIMESTAMP WITH TIME ZONE,
    TIEMPO_PERMANENCIA_MINUTOS  BIGINT,
    ESTADO                      VARCHAR(30) NOT NULL,
    CONSTRAINT FK_MOVIMIENTO_VEHICULO FOREIGN KEY (VEHICULO_ID) REFERENCES VEHICULO (ID),
    CONSTRAINT FK_MOVIMIENTO_ESPACIO FOREIGN KEY (ESPACIO_ID) REFERENCES ESPACIO (ID)
);

CREATE INDEX IDX_MOVIMIENTO_VEHICULO ON MOVIMIENTO (VEHICULO_ID);
CREATE INDEX IDX_MOVIMIENTO_ESTADO ON MOVIMIENTO (ESTADO);
